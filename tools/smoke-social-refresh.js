// Real phone events and persistence across the four social apps.
const fs = require('fs');
const path = require('path');
const H = require('./harness');
const r = H.makeReport('SOSYAL UYGULAMALAR');
const { dom, errors } = H.bootDom(fs.readFileSync(path.join(__dirname, '../KARMA-Oyun.html'), 'utf8'), { seed: 20261027 });
H.whenReady(dom).then(async K => {
  const ok = r.ok.bind(r), d = dom.window.document;
  const click = selector => { const el = d.querySelector(selector); if (!el) throw new Error('Missing control: ' + selector); el.click(); return el; };
  const top = () => K.phone.views.at(-1);
  K.ui.closeModal(); K.contacts.ensureRoster();
  K.phone.openApp('x');
  const xp = K.social.playerPost('x', 'Benzersiz arama <deneme>', 'reach').post;
  K.phone.openApp('x', { tab: 'explore' });
  const search = d.querySelector('[data-x-search]'); search.value = 'Benzersiz arama'; search.dispatchEvent(new dom.window.Event('input'));
  ok('X araması gerçek gönderiyi bulur ve HTML metnini kaçırır', d.querySelector('[data-x-results]').textContent.includes('<deneme>') && !d.querySelector('[data-x-results] deneme'));
  search.value = 'bulunmayacak-xyz'; search.dispatchEvent(new dom.window.Event('input'));
  ok('X araması ilgisiz gönderiyi göstermez', !d.querySelector('[data-x-results]').textContent.includes('Benzersiz'));
  K.phone.openApp('x');
  click(`[data-pact="like"][data-arg="x_${xp.id}"]`);
  K.load(); ok('Beğeni tıklaması yüklemeden sonra korunur', K.interactions.isLiked('x_' + xp.id));
  K.socialActions.hide('x', xp.id); K.load();
  ok('Gizleme kaydedilir ve akıştan kaldırır', !K.phone.appById('x').feedHTML().includes(xp.id));
  K.socialActions.preferences('x'); click('[data-pact="reset-hidden"]');
  ok('Gizleme geri alınabilir', K.socialActions.visible('x', xp));
  K.socialActions.share('x', xp); click('[data-pact="send-share"]');
  const person = d.querySelector('[data-pact="send-person"]'), recipient = person.dataset.arg, picker = top(), before = K.state.player.messagesSentToday;
  person.click(); picker.onAction('send-person', person);
  ok('Paylaşım doğru kişiye bir kere gönderilir', K.state.player.messagesSentToday === before + 1 && K.thread(recipient).messages.some(m => m.text === xp.authorName + ': ' + xp.text));
  K.state.player.messagesSentToday = K.ECON.dailyMessageLimit;
  K.socialActions.sendPicker('limit denemesi'); click('[data-pact="send-person"]');
  ok('Paylaşım günlük mesaj sınırını aşmaz', K.state.player.messagesSentToday === K.ECON.dailyMessageLimit && top().title === 'Mesajla gönder');
  let copied;
  Object.defineProperty(dom.window.navigator, 'clipboard', { configurable: true, value: { writeText: async text => { copied = text; } } });
  await K.socialActions.copy('gerçek içerik'); ok('Pano doğru metni alır', copied === 'gerçek içerik');
  dom.window.navigator.clipboard.writeText = async () => { throw new Error('denied'); };
  await K.socialActions.copy('<manuel>'); ok('Pano reddedilince seçilebilir metin sunulur', d.querySelector('textarea[readonly]').value === '<manuel>'); K.ui.closeModal();
  K.phone.openApp('instagram');
  ok('Instagram referans sekme sırası', top().tabs.map(t => t.id).join(',') === 'feed,reels,inbox,explore,profile');
  click('[data-tab="inbox"]'); ok('Mesaj sekmesi gerçek gelen kutusunu açar', K.phone.views.length > 1 && K.phone.views[0].activeTab === 'feed');
  K.phone.openApp('instagram', { tab: 'reels' });
  const reel = click('[data-pact="reel-cmt"]');
  d.querySelector('[data-social-comment]').value = 'Gerçek yorum <3'; click('[data-pact="send-comment"]');
  K.load(); ok('Reels yorumu kaydedilir', K.state._comments['reel_' + reel.dataset.arg][0].text === 'Gerçek yorum <3');
  K.phone.openApp('youtube'); const yt = K.phone.appById('youtube'), video = yt.allVideos()[0];
  ok('YouTube ilk videodan sonra Shorts sunar', d.querySelector('[data-yt-list]').children[1].classList.contains('yt-short-shelf'));
  click('[data-pact="yt-short-open"][data-arg="1"]'); ok('Shorts kartı seçilen videoyu açar', top().activeTab === 'shorts' && yt.shortIndex(10) === 1);
  K.phone.openApp('youtube'); click('[data-pact="yt-search-focus"]');
  const ys = d.querySelector('[data-yt-search]'); ys.value = 'eşleşmeyenxyz'; ys.dispatchEvent(new dom.window.Event('input'));
  ok('YouTube aramada eski akışı gizler', d.querySelector('[data-yt-list]').hidden); ys.value = ''; ys.dispatchEvent(new dom.window.Event('input'));
  ok('Arama temizlenince akış geri gelir', !d.querySelector('[data-yt-list]').hidden);
  K.state.player.watchHistory = [video.id]; K.interactions.toggleSave('yt_' + video.id); K.phone.openApp('youtube', { tab: 'library' });
  ok('Siz ekranında gerçek geçmiş ve kitaplık bulunur', d.querySelector('.yt-history-card').textContent.includes(video.title) && d.querySelector('.yt-library').textContent.includes('1 video'));
  K.socialActions.hide('youtube', video.id); ok('YouTube gizlenen videoyu akışa koymaz', !yt.listFor('clip').includes('data-arg="' + video.id + '|'));
  ok('Gizlenen video Shorts rafından da kalkar', !yt.shortVideos().some(v => v.id === video.id));
  K.phone.openApp('tiktok'); click('[data-tab="create"]');
  const tt = K.phone.appById('tiktok'), count = K.state.feed.tiktok.length;
  click('[data-pact="publish-video"]'); ok('Boş TikTok gönderisi yayınlanmaz', K.state.feed.tiktok.length === count);
  d.querySelector('[data-tt-caption]').value = 'Yeni kısa video'; click('[data-pact="publish-video"]');
  ok('Oluşturma profil sekmesine döner', top().activeTab === 'mine'); K.load();
  const fresh = K.state.feed.tiktok.find(p => p.text === 'Yeni kısa video');
  ok('Yeni gönderi kayıtta ve video akışında bulunur', !!fresh && tt.videos().some(v => v.id === fresh.id));
  tt.createVideo({ title: 'Seçilen ses' }); d.querySelector('[data-tt-caption]').value = 'Sesli gönderi'; click('[data-pact="publish-video"]'); K.load();
  ok('Seçilen ses kaydedilir ve gösterilir', tt.videos().some(v => v.title === 'Sesli gönderi' && v.soundTitle === 'Seçilen ses') && tt.forYouHTML().includes('Seçilen ses'));
  tt.makeDuet(video.id, 'duet'); K.load(); ok('Duet kaynağı yüklemeden sonra korunur', K.state.feed.tiktok.some(p => p.ofVideoId === video.id && p.duetOf));
  for (const id of ['x', 'instagram', 'youtube', 'tiktok']) {
    K.phone.openApp(id);
    ok(id + ' görünümü hatasız çizilir', !d.querySelector('.app-body').textContent.includes('Bu ekran yüklenemedi'));
  }
  r.setRuntime(errors); r.report();
}).catch(e => { console.error(e); process.exitCode = 1; }).finally(() => dom.window.close());
